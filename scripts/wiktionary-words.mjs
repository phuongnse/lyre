// Generates the core's Wiktionary list of Vietnamese multi-syllable words (D18).
//
// Usage: node scripts/wiktionary-words.mjs <dump.jsonl> [output]
//
// Reads a kaikki.org Vietnamese dump that was downloaded from DUMP_URL beforehand.
// The dump must match DUMP_SHA256: kaikki.org replaces its file in place, so only a
// saved copy can be pinned. Keeps the Vietnamese headwords of two or more syllables,
// each made of Latin-script letters only, and leaves out proverbs. Writes them
// lowercase and NFC, one per line, deduplicated by the core's matching key and
// sorted. The output defaults to core/lyre-core/src/words/wiktionary_words.txt.
// On a hash mismatch it prints both hashes to stderr, exits 1 and writes nothing.
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

export const DUMP_URL = 'https://kaikki.org/dictionary/Vietnamese/kaikki.org-dictionary-Vietnamese.jsonl'
export const DUMP_DATE = '2026-10-03'
export const DUMP_SHA256 = 'ba64fae8301bf3f383a82bb178f2370309d31b3bcb3a92e9b0c9e04aeb6ecc16'

const scriptRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const defaultOutput = path.join(scriptRoot, 'core/lyre-core/src/words/wiktionary_words.txt')

// The Vietnamese tone marks, as combining characters: grave, acute, tilde, hook above and dot below.
const toneMarks = ['̀', '́', '̃', '̉', '̣']

const latinSyllable = /^[\p{Script=Latin}\p{M}]+$/u

/** The SHA-256 of a file, as lowercase hex. */
export function sha256OfFile(file) {
  return createHash('sha256').update(readFileSync(file)).digest('hex')
}

/** The core's matching key of a word: syllable_key in lyre-core's words.rs, per syllable. */
export function matchingKey(word) {
  return word
    .split(' ')
    .map((syllable) => {
      const tones = []
      let toneless = ''
      for (const c of syllable.toLowerCase().normalize('NFD')) {
        if (toneMarks.includes(c)) {
          tones.push(c)
        } else {
          toneless += c
        }
      }
      return toneless.normalize('NFC') + tones.join('')
    })
    .join(' ')
}

/** The list's words from the lines of a dump: kept, deduplicated by matching key and sorted. */
export function wordsFromLines(lines) {
  const kept = new Set()
  for (const line of lines) {
    if (line.trim() === '') {
      continue
    }
    const entry = JSON.parse(line)
    if (entry.lang_code !== 'vi' || entry.pos === 'proverb' || typeof entry.word !== 'string') {
      continue
    }
    const word = entry.word.normalize('NFC').toLowerCase().trim()
    const syllables = word.split(' ')
    if (syllables.length >= 2 && syllables.every((syllable) => latinSyllable.test(syllable))) {
      kept.add(word)
    }
  }
  const byKey = new Map()
  for (const word of [...kept].sort(compare)) {
    const key = matchingKey(word)
    if (!byKey.has(key)) {
      byKey.set(key, word)
    }
  }
  return [...byKey.values()].sort(compare)
}

// Plain code unit order, so the output does not depend on the locale.
function compare(a, b) {
  return a < b ? -1 : a > b ? 1 : 0
}

/** Writes the list from the dump at dumpPath to outPath. Throws, writing nothing, on a hash mismatch. */
export function generate(dumpPath, outPath, expectedSha = DUMP_SHA256) {
  const actualSha = sha256OfFile(dumpPath)
  if (actualSha !== expectedSha) {
    throw new Error(
      [
        `The dump's SHA-256 does not match the pinned hash.`,
        `Expected ${expectedSha} (kaikki.org dump of ${DUMP_DATE}).`,
        `Actual   ${actualSha} (${dumpPath}).`,
      ].join('\n'),
    )
  }
  const words = wordsFromLines(readFileSync(dumpPath, 'utf8').split('\n'))
  const header = [
    '# Vietnamese multi-syllable words from English Wiktionary.',
    '# Licensed under CC BY-SA 4.0, not under the MIT licence of the code.',
    '# See wiktionary_words.NOTICE.md.',
    '# Generated by scripts/wiktionary-words.mjs. Do not edit by hand.',
    `# Source: ${DUMP_URL}`,
    `# Dump date: ${DUMP_DATE}`,
    `# Dump SHA-256: ${expectedSha}`,
  ]
  writeFileSync(outPath, [...header, ...words].join('\n') + '\n')
  return words.length
}

function main(args) {
  const [dumpPath, outPath = defaultOutput] = args
  if (dumpPath === undefined) {
    console.error('Usage: node scripts/wiktionary-words.mjs <dump.jsonl> [output]')
    return 1
  }
  try {
    const count = generate(dumpPath, outPath)
    console.log(`Wrote ${count} words to ${outPath}.`)
    return 0
  } catch (error) {
    console.error(error.message)
    return 1
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2))
}
